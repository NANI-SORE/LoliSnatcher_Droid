import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import 'loc_native.dart';

Future<bool> buildAndroidLocalizations({bool check = false}) async {
  final source = await readNativeLocalizations('downloadNotifications');
  final keys = source.keys;
  var upToDate = true;
  for (final locale in source.locales) {
    final folder = locale == nativeBaseLocale
        ? 'values'
        : locale == 'ru-RU'
        ? 'values-ru'
        : 'values-b+${locale.replaceAll('-', '+')}';
    final resource = File(p.join('android', 'app', 'src', 'main', 'res', folder, 'download_notifications.xml'));
    final xml = StringBuffer('<?xml version="1.0" encoding="utf-8"?>\n')
      ..writeln('<!-- Generated by loc_build.dart from assets/i18n/*.json. -->')
      ..writeln('<resources>');
    for (final key in keys) {
      final name = key.replaceAllMapped(RegExp('[A-Z]'), (m) => '_${m[0]!.toLowerCase()}');
      final value = (source.translations[locale]![key] ?? source.base[key]!)
          .replaceAll(r'\', r'\\')
          .replaceAll('"', r'\"')
          .replaceAll("'", r"\'")
          .replaceAll('\n', r'\n');
      xml.writeln(
        '    <string name="download_notification_$name" formatted="false">"${htmlEscape.convert(value)}"</string>',
      );
    }
    xml.writeln('</resources>');
    final output = xml.toString();
    if (await resource.exists() && await resource.readAsString() == output) continue;
    if (check) {
      stderr.writeln('${resource.path} is stale. Run dart run loc_build.dart --android-only.');
      upToDate = false;
      continue;
    }
    await resource.parent.create(recursive: true);
    await resource.writeAsString(output);
    stdout.writeln('Generated ${resource.path}.');
  }
  return upToDate;
}
